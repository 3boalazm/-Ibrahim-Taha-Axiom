#!/usr/bin/env node
/**
 * Copies the build's /chat/knowledge.json (approved content, see src/utils/chat-knowledge.ts)
 * into server/knowledge.mjs, the module the assistant's function imports. Committing the copy
 * means the function always has the knowledge, on previews too, without fetching its own site.
 *
 *   npm run build && npm run chat:knowledge
 *
 * tests/chat.test.mjs fails when the copy differs from the build, so a content change that
 * forgets this step cannot reach the assistant out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BUILT_PATH = join(ROOT, 'dist', 'chat', 'knowledge.json');
export const MODULE_PATH = join(ROOT, 'server', 'knowledge.mjs');

/** The module source for a parsed knowledge.json. */
export function renderKnowledgeModule(knowledge) {
  return [
    '// Generated by `npm run chat:knowledge` from dist/chat/knowledge.json. Do not edit by hand:',
    '// change the approved data, rebuild, and regenerate (tests/chat.test.mjs checks they match).',
    `export default ${JSON.stringify(knowledge, null, 2)};`,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const knowledge = JSON.parse(readFileSync(BUILT_PATH, 'utf8'));
  writeFileSync(MODULE_PATH, renderKnowledgeModule(knowledge));
  console.log(`wrote ${MODULE_PATH} (${knowledge.chars} characters of site content)`);
}
